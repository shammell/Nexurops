/** Create a new client (fields the caller must / may supply). */
export interface CreateClientInput {
  name: string;
  company?: string | null;
  email: string;
  phone?: string | null;
}

/** Partial update of an existing client. */
export interface UpdateClientInput {
  id: string;
  name?: string;
  company?: string | null;
  email?: string;
  phone?: string | null;
  status?: "ACTIVE" | "INACTIVE" | "CHURNED";
}

/** Create a new project. budget is optional (matches schema nullable). */
export interface CreateProjectInput {
  title: string;
  description?: string | null;
  budget?: number | null;
  clientId: string;
  orderId?: string | null;
  startDate?: Date | null;
  deadline?: Date | null;
}

/** Partial update of an existing project. */
export interface UpdateProjectInput {
  id: string;
  title?: string;
  description?: string | null;
  status?: "BACKLOG" | "IN_PROGRESS" | "REVIEW" | "COMPLETED" | "CANCELLED";
  budget?: number | null;
  startDate?: Date | null;
  deadline?: Date | null;
}

/** Create a new order. */
export interface CreateOrderInput {
  clientId: string;
  serviceId: string;
  totalAmount: number;
}

/** Create a new invoice. */
export interface CreateInvoiceInput {
  clientId: string;
  projectId?: string | null;
  orderId?: string | null;
  amount: number;
  tax?: number;
  totalAmount: number;
  currency?: string;
  dueDate: Date;
  notes?: string | null;
}

/** Mark an invoice as paid. */
export interface PayInvoiceInput {
  id: string;
  stripeInvoiceId?: string;
}

